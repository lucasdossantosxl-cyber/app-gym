def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    work = os.path.abspath(sys.argv[1])
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    assets = os.path.join(root, "app", "src", "main", "assets")
    os.makedirs(os.path.join(assets, "ex"), exist_ok=True)
    os.makedirs(os.path.join(work, "orig"), exist_ok=True)

    index = os.path.join(work, "exercises.json")
    if not os.path.exists(index):
        subprocess.run(["curl", "-sSfL", "-o", index, RAW + "/dist/exercises.json"], check=True)
    known = {x["id"] for x in json.load(open(index, encoding="utf-8"))}

    ids = [e[0] for e in E]
    assert len(ids) == len(set(ids)), "id repetido no catálogo"
    missing = [e[4] for e in E if e[4] not in known]
    assert not missing, "não existem no free-exercise-db: %s" % missing

    out = []
    for slug, nome, grupo, equip, src, aliases, dica in E:
        for frame in (0, 1):
            orig = os.path.join(work, "orig", "%s_%d.jpg" % (slug, frame))
            if not os.path.exists(orig):
                subprocess.run(["curl", "-sSfL", "-o", orig, "%s/exercises/%s/%d.jpg" % (RAW, src, frame)],
                               check=True)
            dest = os.path.join(assets, "ex", "%s_%d.jpg" % (slug, frame))
            subprocess.run(["sips", "-s", "format", "jpeg", "-s", "formatOptions", "55",
                            "--resampleWidth", "420", orig, "--out", dest],
                           check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        out.append({"id": slug, "name": nome, "group": grupo, "equipment": equip,
                    "cardio": grupo == "Cardio", "increment": INCREMENTO[equip],
                    "aliases": aliases.split("|"), "how": dica})

    with open(os.path.join(assets, "exercises.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=0)
        f.write("\n")
    print("%d exercícios, %d fotos" % (len(out), len(out) * 2))


if __name__ == "__main__":
    main()
